  await panel.getByRole('button',{name:'Ask agent to customize',exact:true}).click()
  await panel.locator('#confirm-accept').click()
  await expect.poll(async () => (await skiff.state()).tabs.filter((t) => t.chat).length).toBe(1)
  const chatTab=(await skiff.state()).tabs.find((t) => t.chat)
  const chatId=chatTab.url.slice('skiff://chat/'.length)
  await expect.poll(async () => (await skiff.rpc('ai.chat',{chatId})).status).toBe('ready')
  const grants=await skiff.rpc('grants.list')
