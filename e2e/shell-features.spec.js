async function surface(skiff, file) {
  const matches = (page) => !page.isClosed() && new URL(page.url()).pathname.endsWith(`/browser-tools/${file}`)
  await expect.poll(() => skiff.app.context().pages().some(matches)).toBe(true)
  return skiff.app.context().pages().find(matches)
}
async function tools(skiff, section) {
  await skiff.rpc('ui.openTools', { section })
  const page = await surface(skiff, 'index.html')
  await expect(page.locator('#content h2').first()).toBeVisible()
  return page
}

