  const home = (await skiff.state()).activeSpaceId
  const a = await skiff.rpc('tabs.create', { url: `${skiff.origin}/first` })
  const b = await skiff.rpc('tabs.create', { url: `${skiff.origin}/second` })
  await skiff.rpc('split.set', { ids: [a.id, b.id], ratio: .5 })
  const other = await skiff.rpc('spaces.create', { name: 'Other split' })
  await skiff.rpc('spaces.activate', { id: other.id })
  const c = await skiff.rpc('tabs.create', { url: `${skiff.origin}/first?other` })
  const d = await skiff.rpc('tabs.create', { url: `${skiff.origin}/second?other` })
  await skiff.rpc('split.set', { ids: [c.id, d.id], ratio: .7 })
  await skiff.rpc('spaces.activate', { id: home })
  const panel = await tools(skiff, 'page')
