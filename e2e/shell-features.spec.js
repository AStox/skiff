test('Layer trail collapse hides list descendants but keeps their native pages and frames alive', async ({ skiff }) => {
  const parent = await skiff.rpc('tabs.create', { url: `${skiff.origin}/first` })
  const child = await skiff.rpc('tabs.create', { url: `${skiff.origin}/second`, parentId: parent.id })
  const leaf = await skiff.rpc('tabs.create', { url: `${skiff.origin}/third`, parentId: child.id })
  const pages = [await skiff.page('/first'), await skiff.page('/second'), await skiff.page('/third')]
  for (const [index, page] of pages.entries()) {
    await page.evaluate((index) => {
      window.trailDocumentIdentity = `retained-${index}`
      document.cookie = `trailSurface${index}=retained; Path=/`
    }, index)
  }
  await skiff.rpc('tabs.activate', { id: parent.id })
  const layerSurface = async (file) => {
    const matches = (page) => !page.isClosed() && new URL(page.url()).pathname.endsWith(`/layer/${file}`)
    await expect.poll(() => skiff.app.context().pages().filter(matches).length).toBe(1)
    return skiff.app.context().pages().find(matches)
  }
  const buoy = await layerSurface('buoy.html')
  const nativeAttachments = () => skiff.app.evaluate(({ BrowserWindow }, { urls, ids }) => {
    const desk = BrowserWindow.getAllWindows().find((window) => window.webContents.getURL().endsWith('/layer/index.html'))
    if (!desk) return []
    return desk.contentView.children.flatMap((view) => {
      const url = view.webContents?.getURL()
      if (!url || !URL.canParse(url)) return []
      const parsed = new URL(url)
      if (!urls.includes(url) && !(parsed.pathname.endsWith('/frame.html') && ids.includes(parsed.searchParams.get('tab')))) return []
      const bounds = view.getBounds()
      return [{ id: view.webContents.id, url, visible: bounds.width > 0 && bounds.height > 0 }]
    }).sort((a, b) => a.id - b.id)
  }, { urls: pages.map((page) => page.url()), ids: [parent.id, child.id, leaf.id] })
  await expect.poll(async () => (await nativeAttachments()).length).toBe(6)
  const attached = await nativeAttachments()
  expect(attached.every((view) => view.visible)).toBe(true)
  await buoy.locator('#buoy-tabs').click()
  const list = await layerSurface('tablist.html')
  const parentRow = list.locator(`[data-tab-id="${parent.id}"]`)
  const childRow = list.locator(`[data-tab-id="${child.id}"]`)
  const leafRow = list.locator(`[data-tab-id="${leaf.id}"]`)
  await expect(leafRow).toBeVisible()
  await childRow.getByRole('button', { name: /^Collapse trail for / }).focus()
  await list.keyboard.press('Enter')
  await expect(leafRow).toHaveCount(0)
  await parentRow.getByRole('button', { name: /^Collapse trail for / }).focus()
  await list.keyboard.press('Enter')
  await expect(childRow).toHaveCount(0)
  await expect(parentRow.getByRole('button', { name: /^Expand trail for / })).toBeFocused()
  expect(await nativeAttachments()).toEqual(attached)
  for (const [index, page] of pages.entries()) {
    expect(await page.evaluate(() => window.trailDocumentIdentity)).toBe(`retained-${index}`)
    expect(await page.evaluate(() => document.cookie)).toContain(`trailSurface${index}=retained`)
  }
  // Activating the still-live descendant expands every collapsed ancestor.
  await skiff.rpc('tabs.activate', { id: leaf.id })
  await expect.poll(() => list.isClosed()).toBe(true)
  await buoy.locator('#buoy-tabs').click()
  const reopened = await layerSurface('tablist.html')
  for (const tab of [parent, child, leaf]) await expect(reopened.locator(`[data-tab-id="${tab.id}"]`)).toBeVisible()
  for (const tab of [parent, child]) await expect(reopened.locator(`#trail-toggle-${tab.id}`)).toHaveAttribute('aria-expanded', 'true')
  expect(await nativeAttachments()).toEqual(attached)
  const current = await skiff.state()
  for (const tab of [parent, child, leaf]) expect(current.tabs.find((item) => item.id === tab.id).sessionPartition).toBe(tab.sessionPartition)
  expect(current.activeTabBySpace[current.activeSpaceId]).toBe(leaf.id)
})

