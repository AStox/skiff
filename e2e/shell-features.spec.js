test('profile rename, assignment and external routing use Tools without moving an existing sign-in', async ({ skiff }) => {
  const original = await skiff.rpc('tabs.create', { url: `${skiff.origin}/first` })
  const content = await skiff.page('/first')
  await content.evaluate(() => {
    window.profileSurfaceIdentity = 'original-document'
    document.cookie = 'profileSurface=original'
  })
  await (await skiff.card()).getByRole('button', { name: 'Tools', exact: true }).click()
  const panel = await surface(skiff, 'index.html')
  await panel.getByRole('button', { name: 'Profiles', exact: true }).click()
  await panel.getByLabel('Name', { exact: true }).fill('Work profile')
  await panel.getByRole('button', { name: 'Create profile', exact: true }).click()
  const created = panel.locator('.row').filter({ has: panel.getByRole('heading', { name: 'Work profile', exact: true }) })
  await expect(created).toBeVisible()
  await created.getByLabel('Profile name', { exact: true }).fill('Routed work')
  await created.getByRole('button', { name: 'Rename', exact: true }).click()
  await expect(panel.getByRole('heading', { name: 'Routed work', exact: true })).toBeVisible()
  const profile = (await skiff.state()).profiles.find((item) => item.name === 'Routed work')
  expect(profile).toBeTruthy()
  await panel.getByRole('combobox', { name: 'Space', exact: true }).selectOption(original.spaceId)
  await panel.getByRole('combobox', { name: 'Profile', exact: true }).selectOption(profile.id)
  await panel.getByRole('button', { name: 'Assign profile', exact: true }).click()
  await expect.poll(async () => (await skiff.state()).spaces.find((item) => item.id === original.spaceId).profileId).toBe(profile.id)
  const spaceName = (await skiff.state()).spaces.find((item) => item.id === original.spaceId).name
  await expect(panel.getByText(`New tabs in ${spaceName} use Routed work.`, { exact: true })).toBeVisible()
  // Give the routing form its own explicit destination, independent of the assignment form.
  const host = new URL(skiff.origin).hostname
  await panel.getByLabel('Host pattern', { exact: true }).fill(host)
  await panel.getByRole('combobox', { name: 'Routing space', exact: true }).selectOption(original.spaceId)
  await panel.getByRole('combobox', { name: 'Routing profile', exact: true }).selectOption(profile.id)
  await panel.getByRole('button', { name: 'Add rule', exact: true }).click()
  await expect(panel.locator('.row').filter({ has: panel.getByRole('heading', { name: host, exact: true }) })).toContainText('Routed work')
  expect((await skiff.state()).linkRules.find((rule) => rule.host === host)).toMatchObject({ spaceId: original.spaceId, profileId: profile.id })
  await panel.keyboard.press('Escape')
  const routed = await skiff.rpc('links.open', { url: `${skiff.origin}/second` })
  expect(routed.sessionPartition).toBe(profile.partition)
  expect(routed.sessionPartition).not.toBe(original.sessionPartition)
  const isolated = await skiff.page('/second')
  expect(await isolated.evaluate(() => document.cookie)).not.toContain('profileSurface=original')
  expect((await skiff.state()).tabs.find((item) => item.id === original.id).sessionPartition).toBe(original.sessionPartition)
  expect(await content.evaluate(() => window.profileSurfaceIdentity)).toBe('original-document')
  expect(await content.evaluate(() => document.cookie)).toContain('profileSurface=original')
})
