  await panel.getByRole('button', { name: 'End split', exact: true }).click()
  await expect.poll(async () => (await skiff.state()).splitBySpace[other.id]).toBeFalsy()
  expect((await skiff.state()).splitBySpace[home].ratio).toBe(.4)
