  await skiff.rpc('spaces.activate', { id: other.id })
  await expect(panel.getByRole('slider', { name: 'Split position' })).toHaveValue('70')
  // A queued event from the old control must still target its displayed space.
  await oldControl.evaluate((control) => { control.value = '40'; control.dispatchEvent(new Event('change', { bubbles: true })) })
