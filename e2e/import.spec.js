'use strict'
const { test, expect, snapshot, openImport, next, openInBar } = require('./fixtures')

async function items(skiff) {
  await openImport(skiff)
  await expect(skiff.shell.locator('input[name="arc-profile"]')).toHaveCount(2)
  await next(skiff)
  await expect(skiff.shell.locator('input[name="passwords"]')).not.toBeChecked()
  await expect(skiff.shell.locator('input[name="logins"]')).not.toBeChecked()
}
const identities = (state) => state.tabs.map(({ id, spaceId, sessionPartition, arcSourceId, arcSourceKind }) => ({ id, spaceId, sessionPartition, arcSourceId, arcSourceKind }))

test('multi-profile tabs import: clear/all/back, review, asleep results, repeat and modal page restoration', async ({ skiff }) => {
  const shell = skiff.shell
  await shell.locator('#empty-new-tab').click()
  await openInBar(skiff, `${skiff.origin}/existing`)
  const page = await skiff.page()
  await expect(page.getByRole('heading')).toHaveText('Local fixture page')
  await expect.poll(async () => (await skiff.state()).tabs[0].loading).toBe(false)
  await expect.poll(async () => (await skiff.state()).tabs[0].favicon).toMatch(/^\.\.\/favicons\//)
  await page.evaluate(() => { document.cookie = 'session=main' })
  await expect.poll(() => skiff.attached()).toBeGreaterThan(0)
  const before = await skiff.state()
  await openImport(skiff)
  await expect.poll(() => skiff.attached()).toBe(0)
  await expect(shell.locator('#arc-title')).toBeFocused()
  await shell.getByRole('button', { name: 'Clear selection', exact: true }).click()
  await expect(shell.locator('#arc-next')).toBeDisabled()
  await expect(shell.locator('input[name="arc-profile"]:checked')).toHaveCount(0)
  await shell.getByRole('button', { name: 'Select all', exact: true }).click()
  await expect(shell.locator('input[name="arc-profile"]:checked')).toHaveCount(2)
  await snapshot(shell.locator('#arc-import'), 'import-profiles.png')
  await next(skiff)
  for (const name of ['passwords', 'logins']) await expect(shell.locator(`input[name="${name}"]`)).not.toBeChecked()
  await shell.locator('input[name="openTabs"]').uncheck()
  await shell.locator('#arc-back').click()
  await expect(shell.locator('input[name="arc-profile"]:checked')).toHaveCount(2)
  await next(skiff)
  await expect(shell.locator('input[name="openTabs"]')).not.toBeChecked()
  await shell.locator('input[name="openTabs"]').check()
  await next(skiff)
  await expect(shell.locator('#arc-content')).toContainText('Do not import')
  await expect(shell.locator('#arc-content')).toContainText('Personal')
  await expect(shell.locator('#arc-content')).toContainText('Work')
  await snapshot(shell.locator('#arc-import'), 'import-review.png')
  const requestCount = skiff.requests.length
  await next(skiff)
  await expect(shell.locator('#arc-content .import-profile-result')).toHaveCount(2)
  await expect(shell.locator('#arc-content')).toContainText('Not selected')
  const after = await skiff.state()
  expect(after.tabs.length - before.tabs.length).toBe(6)
  expect(after.spaces.length - before.spaces.length).toBe(2)
  const imported = after.tabs.filter((tab) => tab.arcSourceId)
  expect(new Set(imported.map((tab) => tab.sessionPartition)).size).toBe(2)
  expect(imported.every((tab) => tab.sessionPartition.startsWith('persist:arc-'))).toBe(true)
  expect(imported.filter((tab) => tab.folder === 'Reference folder')).toHaveLength(2)
  // The imported tabs stay asleep. Their site is asked once for its icon, without the browsing session's cookies.
  const lookup = ['/favorite?profile=0']
  await expect.poll(() => skiff.requests.slice(requestCount)).toEqual(lookup)
  await expect.poll(async () => (await skiff.state()).tabs.every((tab) => tab.favicon)).toBe(true)
  expect(skiff.cookied).not.toContain(lookup[0])
  expect((await skiff.audit()).protectedReads).toEqual([])
  expect((await skiff.audit()).decisions).toEqual([])
  await snapshot(shell.locator('#arc-import'), 'import-results.png')
  await next(skiff) // Import again resets optional sensitive categories.
  await expect(shell.locator('input[name="arc-profile"]:checked')).toHaveCount(2)
  await next(skiff)
  await expect(shell.locator('input[name="passwords"]')).not.toBeChecked()
  await expect(shell.locator('input[name="logins"]')).not.toBeChecked()
  await next(skiff)
  await next(skiff)
  await expect(shell.locator('#arc-content .import-profile-result')).toHaveCount(2)
  expect(identities(await skiff.state())).toEqual(identities(after))
  await shell.locator('#arc-cancel').click()
  await expect(shell.locator('#arc-import')).not.toBeVisible()
  await expect.poll(() => skiff.attached()).toBeGreaterThan(0)
  await expect(shell.locator('#import-arc')).toBeFocused()
  await expect(page.getByRole('textbox', { name: 'Page text' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Page text' }).fill('Restored native view')
  await expect(page.getByRole('textbox', { name: 'Page text' })).toHaveValue('Restored native view')
  expect(skiff.requests.slice(requestCount)).toEqual(lookup)
})

for (const condition of ['missing', 'malformed']) {
  test.describe(`${condition} Arc metadata`, () => {
    test.use({ fixtureOptions: { [condition]: true } })
    test('shows recoverable error and retries repaired fixture', async ({ skiff }) => {
      await openImport(skiff)
      await expect(skiff.shell.locator('#arc-error')).toContainText('Arc could not be read')
      await expect(skiff.shell.locator('#arc-next')).toHaveText('Try again')
      expect((await skiff.audit()).protectedReads).toEqual([])
      await snapshot(skiff.shell.locator('#arc-import'), `import-${condition}.png`)
      skiff.repairArc()
      await next(skiff)
      await expect(skiff.shell.locator('input[name="arc-profile"]')).toHaveCount(2)
      await skiff.shell.keyboard.press('Escape')
      await expect(skiff.shell.locator('#arc-import')).not.toBeVisible()
      expect((await skiff.state()).tabs).toHaveLength(0)
    })
  })
}

test.describe('macOS native sensitive-data consent', () => {
  test.skip(process.platform !== 'darwin', 'Production intentionally supports protected Arc import only on macOS; never override platform to fake coverage.')
  test('native cancellation records one denial and performs zero protected reads or state writes', async ({ skiff }) => {
    await items(skiff)
    await skiff.shell.locator('input[name="passwords"]').check()
    await skiff.shell.locator('input[name="logins"]').check()
    await next(skiff)
    const before = await skiff.state()
    await next(skiff)
    await expect(skiff.shell.locator('#arc-status')).toContainText('Import cancelled')
    expect(await skiff.state()).toEqual(before)
    const audit = await skiff.audit()
    expect(audit.decisions).toHaveLength(1)
    expect(audit.decisions[0]).toMatchObject({ response: 0 })
    expect(audit.decisions[0].detail).toContain('Personal, Work')
    expect(audit.protectedReads).toEqual([])
    expect(audit.keychainAttempts).toEqual([])
    await snapshot(skiff.shell.locator('#arc-import'), 'import-native-cancel.png')
    await skiff.shell.locator('#arc-cancel').click()
  })
  test.describe('approved synthetic SQLite warning', () => {
    test.use({ fixtureOptions: { consent: 1 } })
    test('keeps successful tabs and both profiles with partial database warnings', async ({ skiff }) => {
      await items(skiff)
      await skiff.shell.locator('input[name="logins"]').check()
      await next(skiff)
      await next(skiff)
      await expect(skiff.shell.locator('.import-profile-result')).toHaveCount(2)
      await expect(skiff.shell.locator('#arc-content')).toContainText('could not be read')
      expect((await skiff.state()).tabs).toHaveLength(6)
      const audit = await skiff.audit()
      expect(audit.decisions).toHaveLength(1)
      expect(audit.decisions[0].response).toBe(1)
      expect(audit.protectedReads.length).toBeGreaterThan(0)
      expect(audit.keychainAttempts).toEqual([])
      await snapshot(skiff.shell.locator('#arc-import'), 'import-partial-warnings.png')
      for (const profile of ['Personal', 'Work']) {
        const result = skiff.shell.locator('.import-profile-result').filter({ has: skiff.shell.getByRole('heading', { name: profile, exact: true }) })
        await expect(result).toContainText('could not be read')
        await expect(result).toContainText('Not selected')
      }
    })
  })
})
