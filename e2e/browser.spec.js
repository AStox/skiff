test('tabs opened from a page nest under their opener, lift when it closes, and cycle in the order shown', async ({ skiff }) => {
  const root = await skiff.rpc('tabs.create', { url: `${skiff.origin}/trail` })
  const other = await skiff.rpc('tabs.create', { url: `${skiff.origin}/other` })
  const space = (await skiff.state()).activeSpaceId
  const tabsNow = async () => (await skiff.state()).tabs
  const parents = async () => (await tabsNow()).map((tab) => [tab.id, tab.parentId || ''])
  const current = async () => (await skiff.state()).activeTabBySpace[space]
  await expect.poll(async () => (await tabsNow()).find((tab) => tab.id === other.id).title).toBe('Fixture reading')
  await skiff.rpc('tabs.activate', { id: root.id })
  const follow = async (path) => {
    await (await skiff.page(path)).getByRole('link', { name: 'Open in new tab' }).click()
    let tab
    await expect.poll(async () => (tab = (await tabsNow()).find((item) => item.url === `${skiff.origin}/next${path}`))).toBeTruthy()
    await expect.poll(current).toBe(tab.id)
    await expect.poll(async () => (await tabsNow()).find((item) => item.id === tab.id).title).toBe('Fixture reading')
    return tab
  }
  const child = await follow('/trail')
  expect(await parents()).toEqual([[root.id, ''], [other.id, ''], [child.id, root.id]])
  const grandchild = await follow('/next/trail')
  expect(await parents()).toEqual([[root.id, ''], [other.id, ''], [child.id, root.id], [grandchild.id, child.id]])
  await expect.poll(async () => (await tabsNow()).some((tab) => tab.loading)).toBe(false)
  const shown = [root.id, child.id, grandchild.id, other.id]
  for (let step = 1; step <= shown.length; step++) {
    await skiff.shortcut('Ctrl+Tab')
    await expect.poll(current).toBe(shown[(shown.indexOf(grandchild.id) + step) % shown.length])
  }
  const card = await skiff.card()
  const row = card.locator(`#list [data-tab-id="${child.id}"]`)
  await row.hover()
  await row.getByRole('button', { name: 'Close tab', exact: true }).click()
  await expect.poll(parents).toEqual([[root.id, ''], [other.id, ''], [grandchild.id, root.id]])
})

