// A file can load and report a size and still draw nothing, so read the pixels.
const rendered = (image) => expect.poll(() => image.evaluate(async (img) => {
  await img.decode()
  const context = document.createElement('canvas').getContext('2d')
  context.drawImage(img, 0, 0)
  return context.getImageData(0, 0, 300, 150).data.some(Boolean)
}).catch(() => false)).toBe(true)
// One trackpad flick: finger travel, then momentum that only decays. Real elapsed time between events is intentional.
const FLICK = [14, 34, 40, 34, 28, 22, 17, 13, 10, 8, 6, 4, 3, 2]
async function flick(card, deltas = FLICK) {
  for (const delta of deltas) {
    await card.mouse.wheel(delta, 0)
    await card.waitForTimeout(16)
  }
}

test('browser identity modes apply per persistent profile only after restart', async ({ skiff }) => {
  test.setTimeout(90_000)
  const identify = async (tab) => {
    await skiff.rpc('tabs.activate', { id: tab.id })
    const route = new URL(tab.url).pathname
    const page = await skiff.page(route)
    await expect(page.getByRole('heading', { name: 'Local fixture page' })).toBeVisible()
    const observed = await page.evaluate(() => ({ userAgent: navigator.userAgent, hints: navigator.userAgentData?.toJSON(), cookie: document.cookie }))
    await expect.poll(() => skiff.identities.get(route)?.userAgent).toBe(observed.userAgent)
    const preferences = await skiff.app.evaluate(({ webContents }, url) => {
      const wc = webContents.getAllWebContents().find((item) => item.getURL() === url)
      const { sandbox, contextIsolation, nodeIntegration } = wc.getLastWebPreferences()
      return { sandbox, contextIsolation, nodeIntegration, userAgent: wc.getUserAgent() }
    }, tab.url)
    expect(preferences).toEqual({ sandbox: true, contextIsolation: true, nodeIntegration: false, userAgent: observed.userAgent })
    return { ...observed, wire: skiff.identities.get(route), page }
  }
  const home = (await skiff.state()).spaces[0]
  const normal = await skiff.rpc('tabs.create', { url: skiff.origin + '/identity/default', spaceId: home.id })
  const baseline = await identify(normal)
  expect(baseline.userAgent).not.toMatch(/ (Skiff|Electron)\//)
  await baseline.page.evaluate(() => { document.cookie = 'identity=default-profile; Max-Age=3600; Path=/' })
  const preview = await skiff.rpc('import.arc.preview')
  await skiff.rpc('import.arc', { profileIds: preview.profiles.map((profile) => profile.id), categories: { tabs: true, openTabs: false, passwords: false, logins: false }, keepSpaces: false })
  const profiles = (await skiff.state()).spaces.filter((space) => space.sessionPartition?.startsWith('persist:arc-'))
  expect(profiles.length).toBeGreaterThanOrEqual(2)
  const [first, second] = profiles
  await skiff.rpc('settings.set', { browserIdentity: { [first.sessionPartition]: 'native' } })
  // Even a session first opened after the setting change uses the startup map.
  const opted = await skiff.rpc('tabs.create', { url: skiff.origin + '/identity/opted', spaceId: first.id })
  const pending = await identify(opted)
  expect(pending.userAgent).toBe(baseline.userAgent)
  expect(pending.cookie).toBe('')
  await pending.page.evaluate(() => { document.cookie = 'identity=opted-profile; Max-Age=3600; Path=/' })
  expect((await identify(normal)).userAgent).toBe(baseline.userAgent)

  await skiff.restart()
  const native = await identify(opted)
  expect(native.userAgent).toMatch(/ Skiff\/\S+/)
  expect(native.userAgent).toMatch(/ Electron\/\S+/)
  expect(native.userAgent.replace(/ (Skiff|Electron)\/\S+/g, '')).toBe(baseline.userAgent)
  expect(native.hints).toEqual(baseline.hints)
  expect(native.wire.clientHints).toBe(baseline.wire.clientHints)
  expect(native.wire.platform).toBe(baseline.wire.platform)
  expect(native.cookie).toBe('identity=opted-profile')
  const unchanged = await identify(normal)
  expect(unchanged.userAgent).toBe(baseline.userAgent)
  expect(unchanged.cookie).toBe('identity=default-profile')
  expect((await skiff.state()).settings.browserIdentity[first.sessionPartition]).toBe('native')

  // A popup keeps its opener's session; a move joins the new space's profile (and its identity), and archive/restore then keep that session.
  await skiff.rpc('tabs.activate', { id: opted.id })
  await native.page.getByRole('link', { name: 'Open in new tab' }).click()
  let child
  await expect.poll(async () => Boolean(child = (await skiff.state()).tabs.find((tab) => tab.url === skiff.origin + '/next/identity/opted'))).toBe(true)
  expect(child.sessionPartition).toBe(first.sessionPartition)
  expect((await identify(child)).userAgent).toBe(native.userAgent)
  await skiff.rpc('tabs.move', { id: child.id, spaceId: home.id })
  await skiff.rpc('tabs.close', { id: child.id })
  const restored = await skiff.rpc('archive.restore', { id: child.id })
  expect(restored.sessionPartition).toBe(home.sessionPartition)
  expect((await identify(restored)).userAgent).toBe(baseline.userAgent)

  await skiff.rpc('settings.set', { browserIdentity: { [first.sessionPartition]: 'compatible', [second.sessionPartition]: 'native' } })
  expect((await identify(opted)).userAgent).toBe(native.userAgent)
  const sameSession = await skiff.rpc('tabs.create', { url: skiff.origin + '/identity/same-session', spaceId: first.id })
  expect((await identify(sameSession)).userAgent).toBe(native.userAgent)
  const laterSession = await skiff.rpc('tabs.create', { url: skiff.origin + '/identity/later-session', spaceId: second.id })
  const later = await identify(laterSession)
  expect(later.userAgent).toBe(baseline.userAgent)
  expect(later.cookie).toBe('')
  expect((await identify(normal)).userAgent).toBe(baseline.userAgent)

  await skiff.restart()
  const reverted = await identify(opted)
  expect(reverted.userAgent).toBe(baseline.userAgent)
  expect(reverted.cookie).toBe('identity=opted-profile')
  expect((await identify(laterSession)).userAgent).toBe(native.userAgent)
  expect((await identify(normal)).userAgent).toBe(baseline.userAgent)
})

test('tab identity stays pinned through navigation and restart without changing the native profile', async ({ skiff }) => {
  test.setTimeout(120_000)
  await skiff.rpc('settings.set', { browserIdentity: { 'persist:main': 'native' } })
  await skiff.restart()
  const home = (await skiff.state()).spaces[0]
  const inspect = async (tab, route) => {
    await skiff.rpc('tabs.activate', { id: tab.id })
    const page = await skiff.page(route)
    await expect(page.locator('h1')).toHaveText('Local fixture page')
    const userAgent = await page.evaluate(() => navigator.userAgent)
    await expect.poll(() => skiff.identities.get(route)?.userAgent).toBe(userAgent)
    return { page, userAgent }
  }
  const native = await skiff.rpc('tabs.create', { url: `${skiff.origin}/identity/native`, spaceId: home.id })
  const nativePage = await inspect(native, '/identity/native')
  expect(nativePage.userAgent).toMatch(/ Skiff\/\S+.* Electron\/\S+/)
  await nativePage.page.evaluate(() => { document.cookie = 'shared-profile=main; Path=/' })

  const compatible = await skiff.rpc('tabs.create', { url: `${skiff.origin}/identity/before`, spaceId: home.id })
  await inspect(compatible, '/identity/before')
  await skiff.rpc('tabs.navigate', { id: compatible.id, url: `${skiff.origin}/identity/start`, browserIdentity: 'compatible' })
  let tabPage = await skiff.page('/identity/start')
  await expect(tabPage.locator('h1')).toHaveText('Local fixture page')
  const compatibleUA = await tabPage.evaluate(() => navigator.userAgent)
  expect(compatibleUA).not.toMatch(/ (Skiff|Electron)\//)
  expect(await tabPage.evaluate(() => document.cookie)).toContain('shared-profile=main')
  expect((await skiff.state()).tabs.find((tab) => tab.id === compatible.id)).toMatchObject({
    sessionPartition: 'persist:main',
    browserIdentity: 'compatible'
  })
  await expect.poll(() => skiff.identities.get('/identity/start')?.userAgent).toBe(compatibleUA)

  await tabPage.getByRole('link', { name: 'Continue reading' }).click()
  await expect(tabPage).toHaveURL(`${skiff.origin}/second`)
  await expect.poll(() => skiff.identities.get('/second')?.userAgent).toBe(compatibleUA)
  await skiff.rpc('tabs.back', { id: compatible.id })
  await expect(tabPage).toHaveURL(`${skiff.origin}/identity/start`)
  expect(await tabPage.evaluate(() => navigator.userAgent)).toBe(compatibleUA)
  await skiff.rpc('tabs.forward', { id: compatible.id })
  await expect(tabPage).toHaveURL(`${skiff.origin}/second`)
  await skiff.rpc('tabs.reload', { id: compatible.id })
  await expect(tabPage).toHaveTitle('Second fixture')
  await expect.poll(() => skiff.identities.get('/second')?.userAgent).toBe(compatibleUA)

  await skiff.rpc('tabs.navigate', { id: compatible.id, url: `${skiff.origin}/identity/redirect` })
  await expect.poll(async () => (await skiff.state()).tabs.find((tab) => tab.id === compatible.id).url).toBe(`${skiff.origin}/identity/target`)
  tabPage = await skiff.page('/identity/target')
  await expect(tabPage.locator('h1')).toHaveText('Local fixture page')
  await expect.poll(() => skiff.identities.get('/identity/redirect')?.userAgent).toBe(compatibleUA)
  await expect.poll(() => skiff.identities.get('/identity/target')?.userAgent).toBe(compatibleUA)

  await tabPage.getByRole('link', { name: 'Open in new tab' }).click()
  let popup
  await expect.poll(async () => Boolean(popup = (await skiff.state()).tabs.find((tab) => tab.url === `${skiff.origin}/next/identity/target`))).toBe(true)
  expect(popup.sessionPartition).toBe('persist:main')
  expect(Object.hasOwn(popup, 'browserIdentity')).toBe(false)
  const popupPage = await inspect(popup, '/next/identity/target')
  expect(popupPage.userAgent).toBe(nativePage.userAgent)

  await skiff.restart()
  const restoredCompatible = (await skiff.state()).tabs.find((tab) => tab.id === compatible.id)
  const restoredNative = (await skiff.state()).tabs.find((tab) => tab.id === native.id)
  expect(restoredCompatible.browserIdentity).toBe('compatible')
  expect(Object.hasOwn(restoredNative, 'browserIdentity')).toBe(false)
  expect((await skiff.state()).settings.browserIdentity['persist:main']).toBe('native')
  expect((await inspect(restoredCompatible, '/identity/target')).userAgent).toBe(compatibleUA)
  expect((await inspect(restoredNative, '/identity/native')).userAgent).toBe(nativePage.userAgent)
  expect((await inspect(popup, '/next/identity/target')).userAgent).toBe(nativePage.userAgent)
  await skiff.rpc('tabs.navigate', { id: restoredCompatible.id, url: `${skiff.origin}/identity/reset`, browserIdentity: null })
  await skiff.rpc('tabs.activate', { id: restoredCompatible.id })
  const reset = await skiff.page('/identity/reset')
  await expect(reset.locator('h1')).toHaveText('Local fixture page')
  expect(await reset.evaluate(() => navigator.userAgent)).toBe(nativePage.userAgent)
  expect((await skiff.state()).tabs.find((tab) => tab.id === compatible.id).browserIdentity).toBe(null)
})

