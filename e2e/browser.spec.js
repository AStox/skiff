test('directional swipes clamp ends, follow each flick once through its momentum, reject noise and modifiers, and guard modals', async ({ skiff }) => {
  const [a, b, c] = await seedSpaces(skiff)
  const active = () => skiff.state().then((state) => state.activeSpaceId)
  await wheel(skiff, -140, 0)
  await settleGesture(skiff)
  expect(await active()).toBe(a)
  await skiff.shell.locator('#space-head').hover()
  await flick(skiff)
  await settleGesture(skiff)
  expect(await active(), 'One flick and its momentum move one space').toBe(b)
  await wheel(skiff, -40, 0)
  await expect.poll(active).toBe(a)
  await settleGesture(skiff)
  await flick(skiff)
  await flick(skiff)
  await settleGesture(skiff)
  expect(await active(), 'A second flick during the momentum of the first moves a second space').toBe(c)
  await wheel(skiff, 140, 0)
  await settleGesture(skiff)
  expect(await active()).toBe(c)
  await wheel(skiff, -140, 0, '#empty')
  await expect.poll(active).toBe(b)
  await settleGesture(skiff)
  for (const [dx, dy] of [[0, 140], [100, 120], [20, 0]]) {
    await wheel(skiff, dx, dy)
    await settleGesture(skiff)
    expect(await active()).toBe(b)
  }
  for (const key of ['Control', 'Meta', 'Alt', 'Shift']) {
    await skiff.shell.keyboard.down(key)
    try { await wheel(skiff, 140, 0) } finally { await skiff.shell.keyboard.up(key) }
    await settleGesture(skiff)
    expect(await active()).toBe(b)
  }
  await skiff.shortcut('CmdOrCtrl+T')
  const bar = await barReady(skiff)
  await bar.locator('#palette').hover()
  await bar.mouse.wheel(140, 0)
  await settleGesture(skiff)
  expect(await active()).toBe(b)
  await bar.keyboard.press('Escape')
  await expect.poll(() => skiff.barOpen()).toBe(false)
  await openImport(skiff)
  await wheel(skiff, 140, 0, '#arc-content')
  await settleGesture(skiff)
  expect(await active()).toBe(b)
  await skiff.shell.locator('#arc-cancel').click()
  await skiff.shell.locator('#delete-space').click()
  await wheel(skiff, 140, 0, '#confirm-box')
  await settleGesture(skiff)
  expect(await active()).toBe(b)
  await skiff.shell.locator('#confirm-cancel').click()
  const slide = await skiff.shell.evaluate(async (id) => {
    const list = document.getElementById('list')
    await window.skiff.call('spaces.activate', { id })
    for (let frame = 0; frame < 30 && !list.getAnimations().length; frame++) await new Promise(requestAnimationFrame)
    return list.getAnimations().map((animation) => animation.effect.getTiming().duration)
  }, c)
  expect(slide, 'A space change slides the list in briefly').toEqual([130])
})

