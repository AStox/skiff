test('directional swipes follow each flick once through its momentum, reject noise and modifiers, and guard modals', async ({ skiff }) => {
  const [a, b, c] = await seedSpaces(skiff)
  const active = () => skiff.state().then((state) => state.activeSpaceId)
  const card = await skiff.card()
  await card.locator('#chips').hover()
  await flick(card)
  await settleGesture(card)
  expect(await active(), 'One flick and its momentum move one space').toBe(b)
  await wheel(card, -40, 0)
  await expect.poll(active).toBe(a)
  await settleGesture(card)
  await flick(card)
  await flick(card)
  await settleGesture(card)
  expect(await active(), 'Flicks with no pause between them are one gesture and move one space').toBe(b)
  await flick(card)
  await settleGesture(card)
  expect(await active(), 'A flick after a pause moves again').toBe(c)
  await wheel(card, -140, 0, '#list')
  await expect.poll(active).toBe(b)
  await settleGesture(card)
  for (const [dx, dy] of [[0, 140], [100, 120], [20, 0]]) {
    await wheel(card, dx, dy)
    await settleGesture(card)
    expect(await active()).toBe(b)
  }
  for (const key of ['Control', 'Meta', 'Alt', 'Shift']) {
    await card.keyboard.down(key)
    try { await wheel(card, 140, 0) } finally { await card.keyboard.up(key) }
    await settleGesture(card)
    expect(await active()).toBe(b)
  }
  await card.locator('#new-tab').click()
  const bar = await barReady(skiff)
  await bar.locator('#palette-input').hover()
  await bar.mouse.wheel(140, 0)
  await settleGesture(bar)
  expect(await active()).toBe(b)
  await bar.keyboard.press('Escape')
  await expect.poll(() => skiff.barOpen()).toBe(false)
  await openImport(skiff)
  await wheel(card, 140, 0, '#arc-content')
  await settleGesture(card)
  expect(await active()).toBe(b)
  await card.locator('#arc-cancel').click()
  await card.locator('#settings-page-space').click()
  await card.locator('#delete-space').click()
  await wheel(card, 140, 0, '#confirm-box')
  await settleGesture(card)
  expect(await active()).toBe(b)
  await card.locator('#confirm-cancel').click()
  const slide = await card.evaluate(async (id) => {
    const list = document.getElementById('list')
    await window.skiff.call('spaces.activate', { id })
    for (let frame = 0; frame < 30 && !list.getAnimations().length; frame++) await new Promise(requestAnimationFrame)
    return list.getAnimations().map((animation) => animation.effect.getTiming().duration)
  }, c)
  expect(slide, 'A space change slides the list in briefly').toEqual([130])
})

