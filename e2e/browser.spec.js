  await expect(row(other.id).locator('.label')).toHaveText('Fixture reading')
  await rendered(row(other.id).locator('img.favicon'))
  await row(root.id).locator('.row-main').click()
  await expect(row(root.id)).toHaveClass(/current/)
  const rows = () => shell.locator('#list li.row[data-tab-id]').evaluateAll((all) => all.map((item) => [item.dataset.tabId, item.dataset.depth]))
  const follow = async (path) => {
    await (await skiff.page(path)).getByRole('link', { name: 'Open in new tab' }).click()
    let tab
    await expect.poll(async () => (tab = (await skiff.state()).tabs.find((item) => item.url === `${skiff.origin}/next${path}`))).toBeTruthy()
    await expect(row(tab.id)).toHaveClass(/current/)
    await expect(row(tab.id).locator('.label')).toHaveText('Fixture reading')
    await rendered(row(tab.id).locator('img.favicon'))
    return tab
  }
  const child = await follow('/trail')
  expect(await rows()).toEqual([[root.id, '0'], [child.id, '1'], [other.id, '0']])
  const grandchild = await follow('/next/trail')
  expect(await rows()).toEqual([[root.id, '0'], [child.id, '1'], [grandchild.id, '2'], [other.id, '0']])
  await expect.poll(async () => (await skiff.state()).tabs.some((tab) => tab.loading)).toBe(false)
  await snapshot(shell.locator('#sidebar'), 'trails.png', { mask: [shell.locator('#address')] })
