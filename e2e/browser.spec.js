test('a saved icon that loads but draws nothing shows the globe, not an empty tile', async ({ skiff }) => {
  // One 64x64 32bpp BMP entry whose header height is 64 instead of the doubled 128, with no AND mask.
  const ico = Buffer.alloc(6 + 16 + 40 + 64 * 64 * 4, 0x80)
  ico.fill(0, 0, 62)
  ico.set([0, 0, 1, 0, 1, 0, 64, 64, 0, 0, 1, 0, 32, 0])
  ico.writeUInt32LE(ico.length - 22, 14)
  ico.writeUInt32LE(22, 18)
  ico.writeUInt32LE(40, 22)
  ico.writeInt32LE(64, 26)
  ico.writeInt32LE(64, 30)
  ico.writeUInt16LE(1, 34)
  ico.writeUInt16LE(32, 36)
  // The core reuses the file saved for an icon URL, so the fixture page's icon resolves to these bytes.
  const name = crypto.createHash('sha256').update(`${skiff.origin}/icon.png`).digest('hex').slice(0, 24)
  fs.mkdirSync(path.join(skiff.data, 'favicons'), { recursive: true })
  fs.writeFileSync(path.join(skiff.data, 'favicons', `${name}.ico`), ico)
  const tab = await skiff.rpc('tabs.create', { url: `${skiff.origin}/first` })
  await expect.poll(async () => (await skiff.state()).tabs[0].favicon).toBe(`../favicons/${name}.ico`)
  const row = skiff.shell.locator(`#list [data-tab-id="${tab.id}"]`)
  await expect(row.locator('.favicon.letter')).toHaveCount(1)
  await dragTo(skiff, row, skiff.shell.locator('#favorites .drop-zone'))
  const tile = skiff.shell.locator('#favorites .tile')
  await expect(tile.locator('use[href="#i-globe"]')).toHaveCount(1)
  await expect(tile.locator('img')).toHaveCount(0)
})

