'use strict'
const fs = require('node:fs')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const { test, expect, snapshot, barReady } = require('./fixtures')

const fakeAgent = path.join(__dirname, 'fake-agent.js')
// The fixture root rides along as an argument so a leftover agent of this test can be found by its command line.
const command = (skiff) => `'${process.execPath}' '${fakeAgent}' '${skiff.root}'`
const agentPids = (skiff) => execFileSync('ps', ['-eo', 'pid=,args='], { encoding: 'utf8' }).split('\n').filter((line) => line.includes(fakeAgent) && line.includes(skiff.root)).map((line) => Number(line.trim().split(/\s+/)[0]))
const connect = (skiff) => skiff.rpc('settings.set', { ai: { agents: [{ name: 'Fake', command: command(skiff) }] } })
const chatState = (skiff, chatId) => skiff.rpc('ai.chat', { chatId })
const settled = (skiff, chatId) => expect.poll(async () => (await chatState(skiff, chatId)).status).toBe('ready')
const last = (page, selector) => page.locator(selector).last()
const FOOT = (model, effort) => new RegExp(`Model: ${model} Effort: ${effort}$`)

async function fixturePage(skiff, route = '/reading', spaceId) {
  const tab = await skiff.rpc('tabs.create', { url: skiff.origin + route, ...(spaceId && { spaceId }) })
  await skiff.page(route)
  await expect.poll(async () => (await skiff.state()).tabs.find((t) => t.id === tab.id)?.title).toBe('Fixture reading')
  return tab
}

async function openBar(skiff, accelerator = 'CmdOrCtrl+T') {
  await skiff.shortcut(accelerator)
  return barReady(skiff)
}

// The chat tab the bar just opened: the active tab, once it is a conversation.
async function openedChat(skiff) {
  let tab
  await expect.poll(async () => {
    const s = await skiff.state()
    tab = s.tabs.find((t) => t.id === s.activeTabBySpace[s.activeSpaceId] && t.chat)
    return Boolean(tab)
  }).toBe(true)
  const chatId = tab.url.slice('skiff://chat/'.length)
  return { tab, chatId, page: await skiff.chat(chatId) }
}

async function send(chat, text) {
  await chat.locator('#chat-input').click()
  await chat.keyboard.type(text)
  await chat.keyboard.press('Enter')
}

async function useLayer(skiff) {
  const old = skiff.shell
  const closed = old.waitForEvent('close')
  await old.evaluate(() => { window.skiff.call('ui.setShell', { name: 'layer' }) })
  await closed
  await expect.poll(() => !skiff.shell.isClosed()).toBe(true)
  await skiff.shell.waitForLoadState()
}

// Settings > Agents, as a user fills it in: the default preset's name and command typed over.
async function addAgent(settings, skiff, name = 'Fake') {
  await settings.locator('#agent-name').click()
  await settings.keyboard.press('Control+a')
  await settings.keyboard.type(name)
  await settings.locator('#agent-command').click()
  await settings.keyboard.press('Control+a')
  await settings.keyboard.type(command(skiff))
  await expect(settings.locator('#agent-preset')).toHaveValue('')
  await settings.locator('#agent-add').click()
  await expect(settings.locator(`#agents-list li[data-agent="${name}"]`)).toBeVisible()
}

// A question asked before any agent exists (over the API; the bar sends the user to Settings instead) waits in its chat tab.
async function waitingChat(skiff, text) {
  await skiff.rpc('ai.ask', { text })
  const opened = await openedChat(skiff)
  await expect(opened.page.locator('#chat-connect-card')).toBeVisible()
  await expect(opened.page.locator('#chat-pending')).toHaveText(text)
  await expect(opened.page.locator('#chat-composer')).toBeHidden()
  return opened
}

