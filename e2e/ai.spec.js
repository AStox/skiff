  await settled(skiff, chatId)
  expect((await chatState(skiff, chatId)).turns.at(-1).text).toMatch(FOOT('fake-small', 'high'))
  const md = last(chat, '.ai-assistant .ai-md')
  await expect(md.locator('h3')).toHaveText('Three ways to say it')
  await expect(md.locator('li')).toHaveText(['Bold for the point', 'Italic for a linked aside', 'code in a line'])
